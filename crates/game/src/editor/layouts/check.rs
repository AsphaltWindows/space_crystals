//! Whether an object may go into a Starting Layout where the Layout tool puts it, and the ghost that shows it under
//! the cursor. The rules are the sim's (`sc_sim::MapDef::validate`, slice M2-F1), asked of the map as it would be:
//! every layout is valid on its own with "that faction's normal in-game placement rules, minus visibility" (`core/
//! map_editor.md > Starting Layouts > Layout validation`, design change 0097: structures by the placement check in
//! Layout mode, starting units by the unit-start rule) and, on a Skirmish Default map, holds only its faction's
//! Starting Conditions (`> Skirmish Default restriction`). There are no visibility checks and no sight warnings
//! (0097). The editor adds its own two rules for symmetric maps, as for pre-placed objects: an object goes in the
//! editable part, and not across an axis onto its own image.

use std::collections::BTreeSet;

use bevy::prelude::*;
use sc_sim::{
    BuildingOrientation, Faction, LayoutObject, MapDef, MapType, ObjectKind, ScenarioProblem, SlotId, Spawn, SpawnAt,
    StartingConditions, TilePos, TileProblem, WholeProblem,
};

use crate::editor::doc::EditorDoc;
use crate::editor::gesture::Gesture;
use crate::editor::objects::{self, faction_name};
use crate::editor::state::EditorCursor;
use crate::editor::tools::{EditorTools, Tool};

/// Why an object can't go where the Layout tool would put it.
#[derive(Clone, Debug, PartialEq)]
pub enum LayoutRefusal {
    /// The faction has no Starting Conditions yet (plan decision T11): its layouts stay empty.
    NotImplemented(Faction),
    /// `> Skirmish Default restriction`: the kind isn't one of the faction's Starting Conditions.
    NotStarting { kind: ObjectKind, faction: Faction },
    /// `> Skirmish Default restriction`: the layout already holds the `count` objects of the kind that the Starting
    /// Conditions do.
    NoneLeft {
        kind: ObjectKind,
        faction: Faction,
        count: u32,
    },
    /// Its centre lies in the locked part of a symmetric map, which is generated.
    Locked,
    /// It would overlap one of its own symmetric images (the editor's placeholder rule for objects on the axes).
    OverlapsOwnImage,
    /// It breaks the layout rules: the sim's problems of the object.
    Rules(Vec<ScenarioProblem>),
}

impl LayoutRefusal {
    /// Why an object of `kind` can't go there, for the status line.
    pub fn message(&self, kind: ObjectKind) -> String {
        let name = kind.def().name;
        match self {
            LayoutRefusal::NotImplemented(faction) => format!(
                "{}: not implemented yet, its layouts stay empty",
                faction_name(*faction)
            ),
            LayoutRefusal::NotStarting { faction, .. } => {
                let start = StartingConditions::of(*faction)
                    .map(|s| super::missing_text(s.objects))
                    .unwrap_or_default();
                format!(
                    "A Skirmish Default {} layout holds only its Starting Conditions ({start}): no {name}",
                    faction_name(*faction)
                )
            }
            LayoutRefusal::NoneLeft { faction, count, .. } => format!(
                "The layout already has the {} of the {} Starting Conditions",
                super::count_text(kind, *count),
                faction_name(*faction)
            ),
            LayoutRefusal::Locked => {
                format!(
                    "Locked: that part of the map is generated by its symmetry; place the {name} in the bright part"
                )
            }
            LayoutRefusal::OverlapsOwnImage => {
                format!("{name} would overlap its own mirror image: put it away from the axis (placeholder rule)")
            }
            LayoutRefusal::Rules(problems) => match problems.first() {
                Some(problem) => format!("Can't place the {name} there: {}", rule_text(problem)),
                None => format!("Can't place the {name} there"),
            },
        }
    }

    /// The footprint tiles that break a rule of their own (the placement check's tile problems), and whether the
    /// object as a whole breaks one.
    pub fn marked_tiles(&self) -> (BTreeSet<TilePos>, bool) {
        let LayoutRefusal::Rules(problems) = self else {
            return (BTreeSet::new(), true);
        };
        let mut tiles = BTreeSet::new();
        let mut whole = false;
        for problem in problems {
            match problem {
                ScenarioProblem::LayoutPlacement { check, .. } => {
                    tiles.extend(check.tiles.iter().map(|(t, _)| *t));
                    whole |= !check.whole.is_empty();
                }
                _ => whole = true,
            }
        }
        (tiles, whole)
    }
}

/// What rule a layout object's problem says it breaks, in words: the placement check's ("no tile is in the build
/// area", "sloped at tile (3, 4)"), the unit-start rule's, or the Skirmish Default restriction's.
pub fn rule_text(problem: &ScenarioProblem) -> String {
    match problem {
        ScenarioProblem::LayoutPlacement { check, .. } => {
            let mut parts: Vec<String> = check
                .whole
                .iter()
                .map(|w| match w {
                    // A layout's build area is its own Deployment Center's (`> Layout validation`).
                    WholeProblem::OutsideBuildArea => {
                        "no tile is in the build area of the layout's Deployment Center".to_string()
                    }
                    w => w.to_string(),
                })
                .collect();
            for problem in TileProblem::ALL {
                let tiles: Vec<&TilePos> = check
                    .tiles
                    .iter()
                    .filter(|(_, p)| *p == problem)
                    .map(|(t, _)| t)
                    .collect();
                if let Some(first) = tiles.first() {
                    let more = match tiles.len() - 1 {
                        0 => String::new(),
                        n => format!(" and {n} more"),
                    };
                    parts.push(format!("{problem} at tile ({}, {}){more}", first.x, first.y));
                }
            }
            parts.join("; ")
        }
        ScenarioProblem::InvalidLayoutObject { problem, .. } => problem.to_string(),
        ScenarioProblem::LayoutExtra { faction, allowed, .. } => match allowed {
            0 => format!("not in the {} Starting Conditions", faction_name(*faction)),
            n => format!(
                "more than the {n} of the {} Starting Conditions",
                faction_name(*faction)
            ),
        },
        ScenarioProblem::LayoutOverlap { tile, .. } => {
            format!("overlaps another object at tile ({}, {})", tile.x, tile.y)
        }
        problem => problem.to_string(),
    }
}

/// Whether `problem` is one of object `index` of the layout of `faction` at `slot`.
pub fn concerns(problem: &ScenarioProblem, slot: SlotId, faction: Faction, index: usize) -> bool {
    match *problem {
        ScenarioProblem::InvalidLayoutObject {
            slot: s,
            faction: f,
            index: i,
            ..
        }
        | ScenarioProblem::LayoutPlacement {
            slot: s,
            faction: f,
            index: i,
            ..
        }
        | ScenarioProblem::LayoutExtra {
            slot: s,
            faction: f,
            index: i,
            ..
        }
        | ScenarioProblem::LayoutOverlap {
            slot: s,
            faction: f,
            index: i,
            ..
        } => (s, f, i) == (slot, faction, index),
        _ => false,
    }
}

/// Whether `object` may be object `index` of the layout of `faction` at `slot`: in place of that object when the
/// layout has one (a move), else as a new object at its end. Checked in this order: the faction has Starting
/// Conditions; on a Skirmish Default map they hold the kind, and a new object leaves the layout within their count;
/// the object lies in the editable part and not across an axis; and, the layout changed so, the sim's validation
/// finds nothing wrong with it.
pub fn check_object(
    map: &MapDef,
    slot: SlotId,
    faction: Faction,
    index: usize,
    object: &LayoutObject,
) -> Result<(), LayoutRefusal> {
    let Some(start) = StartingConditions::of(faction) else {
        return Err(LayoutRefusal::NotImplemented(faction));
    };
    let Some(layout) = map.slot(slot).map(|s| s.layouts.get(faction)) else {
        return Err(LayoutRefusal::Rules(Vec::new()));
    };
    let kind = object.kind;
    if map.map_type == MapType::SkirmishDefault {
        let count = start.count(kind);
        if count == 0 {
            return Err(LayoutRefusal::NotStarting { kind, faction });
        }
        let others = layout
            .iter()
            .enumerate()
            .filter(|&(i, o)| i != index && o.kind == kind)
            .count();
        if u32::try_from(others).unwrap_or(u32::MAX) >= count {
            return Err(LayoutRefusal::NoneLeft { kind, faction, count });
        }
    }
    let spawn = as_spawn(object);
    if !map.is_spawn_editable(&spawn) {
        return Err(LayoutRefusal::Locked);
    }
    let images = map.spawn_images(&spawn);
    let all: Vec<&Spawn> = std::iter::once(&spawn).chain(&images).collect();
    let footprints: Vec<BTreeSet<TilePos>> = all
        .iter()
        .map(|s| objects::spawn_tiles(s).into_iter().collect())
        .collect();
    if objects::overlaps_own_image(&all, &footprints) {
        return Err(LayoutRefusal::OverlapsOwnImage);
    }
    let mut candidate = map.clone();
    let index = match candidate.slot_mut(slot).map(|s| s.layouts.get_mut(faction)) {
        Some(objects) if index < objects.len() => {
            objects[index] = object.clone();
            index
        }
        Some(objects) => {
            objects.push(object.clone());
            objects.len() - 1
        }
        None => return Err(LayoutRefusal::Rules(Vec::new())),
    };
    let problems: Vec<ScenarioProblem> = candidate
        .validate()
        .into_iter()
        .filter(|p| concerns(p, slot, faction, index))
        .collect();
    if problems.is_empty() {
        Ok(())
    } else {
        Err(LayoutRefusal::Rules(problems))
    }
}

/// A layout object as a neutral spawn: where it lies, for the editor's footprint and symmetry helpers.
pub fn as_spawn(object: &LayoutObject) -> Spawn {
    Spawn {
        orientation: object.orientation,
        ..Spawn::new(object.kind, None, object.at)
    }
}

/// The object the Layout tool would place under the cursor, with what the check says of it.
#[derive(Clone, Debug, PartialEq)]
pub struct LayoutGhost {
    pub kind: ObjectKind,
    pub at: SpawnAt,
    pub orientation: BuildingOrientation,
    /// Where the editor would generate its images, and how they are turned.
    pub images: Vec<(SpawnAt, BuildingOrientation)>,
    pub verdict: Result<(), LayoutRefusal>,
}

/// The Layout tool's ghost, while the cursor is over the map, the tool isn't dragging, and the cursor isn't over an
/// object of the edited layout (a click there selects it).
#[derive(Resource, Default, Debug, PartialEq)]
pub struct LayoutPreview(pub Option<LayoutGhost>);

/// What the ghost was last worked out for: the document's revision, the tools and the object's place.
#[derive(PartialEq)]
pub struct GhostKey {
    revision: u64,
    tools: EditorTools,
    at: Option<SpawnAt>,
}

/// Keeps [`LayoutPreview`] up to date, checking the object only when what it depends on changed: the check runs the
/// sim's validation of the whole map.
pub fn update_layout_preview(
    doc: Res<EditorDoc>,
    tools: Res<EditorTools>,
    cursor: Res<EditorCursor>,
    gesture: Res<Gesture>,
    mut preview: ResMut<LayoutPreview>,
    mut checked: Local<Option<GhostKey>>,
) {
    if !(doc.is_changed() || tools.is_changed() || cursor.is_changed() || gesture.is_changed()) {
        return;
    }
    let map = doc.map();
    let (slot, faction, kind) = (tools.slot, tools.faction, tools.layout_kind);
    let orientation = tools.placed_orientation();
    let pos = cursor
        .0
        .filter(|_| tools.tool == Tool::Layout && gesture.0.is_none())
        .filter(|pos| super::layout_object_at(map, slot, faction, *pos).is_none());
    let at = pos.map(|pos| objects::snap_spawn(kind, orientation, pos));
    let key = GhostKey {
        revision: doc.revision(),
        tools: tools.clone(),
        at,
    };
    if checked.as_ref() == Some(&key) {
        return;
    }
    *checked = Some(key);
    let ghost = at.map(|at| {
        let object = LayoutObject { kind, at, orientation };
        let index = map.slot(slot).map_or(0, |s| s.layouts.get(faction).len());
        let images = map
            .spawn_images(&as_spawn(&object))
            .into_iter()
            .map(|s| (s.at, s.orientation))
            .collect();
        LayoutGhost {
            kind,
            at,
            orientation,
            images,
            verdict: check_object(map, slot, faction, index, &object),
        }
    });
    if preview.0 != ghost {
        preview.0 = ghost;
    }
}
